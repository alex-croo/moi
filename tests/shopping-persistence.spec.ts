import { test, expect } from "@playwright/test";
import { PGlite } from "@electric-sql/pglite";
import { readdir, readFile } from "node:fs/promises";
import { applyPrivateMutation } from "../src/lib/private-mutations";
import { createVault, encryptVault, decryptVault } from "../src/lib/vault-crypto";
import { demoData } from "../src/lib/demo";
import { reconcileCooking } from "../src/lib/cooking-reconcile";
import type { PersonalData } from "../src/lib/private-types";

test("legacy schema: database persists receipt and cooking together with stock, survives reload, and rejects stale or foreign writes", async () => {
  test.setTimeout(60000);
  const db = new PGlite(), owner = "11111111-1111-4111-8111-111111111111", admin = "22222222-2222-4222-8222-222222222222";
  try {
    await db.exec(`create role anon;create role authenticated;create role supabase_auth_admin;create schema auth;create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to authenticated,anon;grant execute on function auth.uid() to authenticated,anon;insert into auth.users values('${owner}','owner@example.test',now()),('${admin}','imalexgauthier@gmail.com',now());`);
    for (const file of (await readdir("supabase/migrations")).filter(f => f.endsWith(".sql") && f < "20261022000000").sort()) await db.exec(await readFile(`supabase/migrations/${file}`, "utf8"));
    await db.exec(`insert into private.members(user_id,role) values('${owner}','member'),('${admin}','admin')`);
    const asUser = async (id: string) => { await db.exec("reset role;set role authenticated"); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); };
    const save = async (revision: number, data: PersonalData) => db.query("select public.save_standard_workspace($1,$2)",[revision,JSON.stringify(data)]);
    const reload = async () => (await db.query<{ data: PersonalData; revision: number }>("select data,revision from public.standard_workspaces")).rows[0];
    const catalog = { recipes: demoData.recipes, ingredients: demoData.ingredients };
    const { recipes: _r, ingredients: _i, ...base } = demoData;
    let personal: PersonalData = { ...base, pantry: [], slots: [{ date: "2026-10-25", slot: "lunch", recipeId: demoData.recipes[0].id }], program: { completed: {}, reflections: {} } };
    const orderId = crypto.randomUUID(), cookId = crypto.randomUUID();
    await asUser(owner);
    personal = applyPrivateMutation(personal, "shopping", { action: "order", id: orderId, mode: "online", grocer: "Private grocer", expectedDate: "2026-10-25", fulfillment: "pickup", lines: [{ ingredientId: "beef-95-raw", quantity: { kind: "count", value: 1, label: "paquet" }, location: "freezer" }] }, catalog);
    personal = applyPrivateMutation(personal, "shopping", { action: "receiveActual", id: orderId, lines: [{ ingredientId: "beef-95-raw", quantity: { kind: "mass", value: 500 }, location: "freezer" }] }, catalog);
    const personalFood = { id: crypto.randomUUID(), name: "Private yogurt", aisle: "dairy", quantity: { kind: "volume", value: 500 } };
    personal = applyPrivateMutation(personal, "shopping", { action: "personalItem", item: personalFood }, catalog);
    personal = applyPrivateMutation(personal, "shopping", { action: "selectMany", range: { start: "2026-10-25", end: "2026-10-31" }, updates: [{ ingredientId: personalFood.id, checked: true }] }, catalog);
    await save(0, personal);
    expect((await reload()).data.shopping?.personalItems).toEqual([personalFood]);
    const received = await reload();
    const undoPreview = applyPrivateMutation(received.data, "shopping", {action:"undoInventory",id:received.data.shopping!.inventoryEvents![0].id}, catalog);
    expect(undoPreview.shopping?.personalItems).toHaveLength(0);
    expect(undoPreview.pantry[0].quantity?.value).toBe(500); expect(received.data.pantry[0].quantity?.value).toBe(500); expect(received.data.shopping?.orders[0].status).toBe("received");
    const cook = { action: "cook", id: cookId, meal: personal.slots[0], portions: 2, includeOptional: false };
    const concurrentlyUpdated = {...received.data, program:{completed:{lesson:'2026-10-24'},reflections:{}}};
    await save(1, concurrentlyUpdated);
    personal = applyPrivateMutation(received.data, "shopping", cook, catalog);
    await expect(save(1, received.data)).rejects.toThrow(/Workspace changed/);
    await expect(save(1, personal)).rejects.toThrow(/Workspace changed/);
    const fresh = await reload();
    expect(reconcileCooking(received.data,fresh.data,catalog,catalog,cook)).toBe('retry');
    personal = applyPrivateMutation(fresh.data, "shopping", cook, catalog);
    await save(fresh.revision, personal);
    expect((await reload()).data.program).toEqual(concurrentlyUpdated.program);
    expect((await reload()).data.pantry[0].quantity?.value).toBe(250);
    expect(reconcileCooking(received.data,(await reload()).data,catalog,catalog,cook)).toBe('acknowledged');
    await asUser(admin);
    expect(await reload()).toBeUndefined();
    await db.query("update public.standard_workspaces set data='{}' where owner_id=$1", [owner]).then(() => { throw Error("direct write unexpectedly allowed"); }, error => expect(String(error)).toMatch(/permission/));
    await asUser(owner);
    const sealed = await createVault(owner, "Synthetic strong phrase for testing 42!", personal);
    await db.query("select public.activate_personal_vault($1,$2)", [3, JSON.stringify(sealed.envelope)]);
    expect(await reload()).toBeUndefined();
    const opened = await decryptVault<PersonalData>(sealed.key, sealed.envelope, owner);
    expect(opened.shopping?.personalItems).toEqual([personalFood]);
    expect(JSON.stringify(sealed.envelope)).not.toContain("Private yogurt");
    const undone = applyPrivateMutation(opened, "shopping", { action: "undoCook", id: cookId }, catalog);
    const updated = await encryptVault(sealed.key, sealed.envelope, undone);
    await db.query("select public.save_personal_vault($1,$2)",[1, JSON.stringify(updated)]);
    const readback = (await db.query<{ envelope: typeof updated }>("select envelope from public.personal_vaults")).rows[0].envelope;
    expect(JSON.stringify(readback)).not.toContain("Private grocer");
    expect((await decryptVault<PersonalData>(sealed.key, readback, owner)).pantry[0].quantity?.value).toBe(500);
    const thaw = { action: "thaw", id: crypto.randomUUID(), itemId: undone.pantry[0].id, amount: 200 };
    const thawed = applyPrivateMutation(undone, "shopping", thaw, catalog);
    const thawEnvelope = await encryptVault(sealed.key, updated, thawed);
    await db.query("select public.save_personal_vault($1,$2)", [2, JSON.stringify(thawEnvelope)]);
    const reloadedThaw = (await db.query<{ envelope: typeof thawEnvelope }>("select envelope from public.personal_vaults")).rows[0].envelope;
    const thawReadback = await decryptVault<PersonalData>(sealed.key, reloadedThaw, owner);
    expect(thawReadback.pantry.find(p => p.location === "freezer")?.quantity?.value).toBe(300);
    expect(thawReadback.pantry.find(p => p.location === "fridge")?.quantity?.value).toBe(200);
    expect(thawReadback.shopping?.thawed).toContain(thaw.id);
    await asUser(admin); expect((await db.query("select envelope from public.personal_vaults")).rows).toHaveLength(0);
  } finally { await db.close(); }
});
