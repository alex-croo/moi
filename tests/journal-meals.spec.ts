import { test, expect } from "@playwright/test";
import { addDays } from "../src/lib/units";

test("distant deliveries enter pantry on receipt; journal Done shares cooking, undo and saved writing", async ({ page }) => {
  test.setTimeout(60000);
  await page.goto("/fr/demo");
  const nav = page.getByRole("navigation", { name: "Navigation principale" });
  const dialog = page.getByRole("dialog");
  await nav.getByRole("button", { name: "Mes menus", exact: true }).click();
  await page.locator(".empty-slot").first().click();
  await page.getByRole("button", { name: "Choisir cette recette", exact: true }).click();
  await nav.getByRole("button", { name: "Liste d’épicerie", exact: true }).click();
  const plannedDate = await page.getByLabel("Début des courses").inputValue();
  const farDate = addDays(plannedDate, 160);
  await page.getByRole("button", { name: "Commander en ligne", exact: true }).click();
  await dialog.getByLabel("Réception prévue").fill(farDate);
  await dialog.getByLabel("Quantité Bœuf haché extra maigre", { exact: true }).fill("500");
  await dialog.getByLabel("Quantité Oignon", { exact: true }).fill("200");
  await dialog.getByRole("button", { name: "J’ai passé ma commande", exact: true }).click();
  await expect(page.locator(".pending-order time")).toHaveAttribute("datetime", farDate);
  // A distant supplier remains visible even when the grocery period changes.
  await page.getByLabel("Fin des courses").fill(addDays(plannedDate, 2));
  await page.getByRole("button", { name: "Afficher", exact: true }).click();
  await expect(page.locator(".pending-order")).toHaveCount(1);
  await nav.getByRole("button", { name: "Mes réserves", exact: true }).click();
  const orders = page.getByRole("region", { name: "Commandes en attente" });
  await expect(orders).toBeVisible();
  await expect(page.locator(".pantry-groups").getByRole("listitem")).toHaveCount(0);
  await orders.getByText("Détails et date", { exact: true }).click();
  await expect(orders.locator(".pending-order-items")).toContainText("500 g");
  await orders.getByLabel("Nouvelle date").fill(addDays(plannedDate, -200));
  await orders.getByRole("button", { name: "Reporter", exact: true }).click();
  await expect(orders).toContainText("Date prévue dépassée");
  await expect(page.locator(".pantry-groups").getByRole("listitem")).toHaveCount(0);
  await orders.getByLabel("Nouvelle date").fill(addDays(farDate, 30));
  await orders.getByRole("button", { name: "Reporter", exact: true }).click();
  await expect(orders.locator("time")).toHaveAttribute("datetime", addDays(farDate, 30));
  await orders.getByText("Détails et date", { exact: true }).click();
  for (const [width, height, label] of [[1280,800,"galaxy-tab"],[390,844,"iphone"],[412,915,"android-phone"],[1024,768,"ipad"]] as const) {
    await page.setViewportSize({ width, height });
    await orders.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `artifacts/pantry-orders-${label}.png`, fullPage: true, animations: "disabled" });
  }
  await page.setViewportSize({ width: 1280, height: 800 });
  await orders.getByRole("button", { name: "J’ai reçu ma commande", exact: true }).click();
  await dialog.getByRole("button", { name: "Confirmer et ajouter aux réserves", exact: true }).click();
  await expect(orders.locator(".pending-order")).toHaveCount(0);
  await expect(orders).toContainText("Commande reçue");
  const beef = page.locator(".pantry-groups").getByRole("listitem").filter({ hasText: "Bœuf haché extra maigre" });
  const onion = page.locator(".pantry-groups").getByRole("listitem").filter({ hasText: "Oignon" });
  await expect(beef).toContainText("500 g");
  await expect(onion).toContainText("200 g");
  await nav.getByRole("button", { name: "Mon journal", exact: true }).click();
  await page.getByRole("button", { name: "Écrire aujourd’hui", exact: true }).click();
  await page.getByLabel("Date du journal").fill(plannedDate);
  await page.getByRole("button", { name: "Ouvrir cette date", exact: true }).click();
  const text = "Un repas préparé à mon rythme.\n\nJe garde mes mots pendant le suivi des réserves.";
  await page.getByLabel("Titre de la page").fill("Ma cuisine du jour");
  await page.getByLabel("Texte du journal").fill(text);
  const meals = page.getByRole("region", { name: "Repas du journal" });
  const done = meals.getByRole("checkbox", { name: "Fait · Déjeuner · Bœuf et oignons", exact: true });
  await expect(done).not.toBeChecked();
  await done.click();
  await dialog.getByRole("button", { name: "Annuler", exact: true }).click();
  await expect(done).not.toBeChecked();
  await done.click();
  await dialog.getByLabel("Portions préparées").fill("4");
  await expect(dialog.locator(".cooking-deductions")).toContainText("500 g");
  await dialog.getByLabel("Portions préparées").fill("2");
  await expect(dialog.locator(".cooking-deductions")).toContainText("250 g");
  await dialog.getByRole("button", { name: "Confirmer la préparation", exact: true }).click();
  await expect(done).toBeChecked();
  await expect(meals).toContainText("2 portions préparées");
  await expect(page.getByLabel("Texte du journal")).toHaveValue(text);
  await expect(page.locator(".journal-autosave-indicator")).toContainText("Enregistré");
  for (const [width, height, label] of [[1280,800,"galaxy-tab"],[390,844,"iphone"],[412,915,"android-phone"],[1024,768,"ipad"]] as const) {
    await page.setViewportSize({ width, height });
    await meals.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const row = meals.locator("li"), check = await done.boundingBox(), bounds = await row.boundingBox();
    expect(check!.x).toBeGreaterThan(bounds!.x);
    expect(check!.x + check!.width).toBeLessThanOrEqual(bounds!.x + bounds!.width);
    await page.screenshot({ path: `artifacts/journal-meals-${label}.png`, fullPage: true, animations: "disabled" });
  }
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByLabel("Date du journal").fill(addDays(plannedDate, 1));
  await page.getByRole("button", { name: "Ouvrir cette date", exact: true }).click();
  await expect(meals).toContainText("Aucun repas prévu");
  await expect(meals.getByRole("checkbox")).toHaveCount(0);
  await nav.getByRole("button", { name: "Mes menus", exact: true }).click();
  await expect(page.locator(".cook-slot-action").first()).toContainText("Cuisiné");
  await nav.getByRole("button", { name: "Mes réserves", exact: true }).click();
  await expect(beef).toContainText("250 g");
  await expect(onion).toContainText("100 g");
  await nav.getByRole("button", { name: "Mon journal", exact: true }).click();
  await page.locator(".journal-page-row").filter({ hasText: "Ma cuisine du jour" }).click();
  await expect(done).toBeChecked();
  await expect(page.getByLabel("Texte du journal")).toHaveValue(text);
  await done.uncheck();
  await expect(done).not.toBeChecked();
  await expect(meals).toContainText("quantités retirées sont rétablies");
  await nav.getByRole("button", { name: "Mes réserves", exact: true }).click();
  await expect(beef).toContainText("500 g");
  await expect(onion).toContainText("200 g");
  await nav.getByRole("button", { name: "Mes menus", exact: true }).click();
  await expect(page.getByRole("button", { name: "J’ai cuisiné", exact: true })).toBeVisible();
});
